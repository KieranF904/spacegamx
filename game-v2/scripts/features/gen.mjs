#!/usr/bin/env node
/**
 * Writes common/src/ships/features/registry.ts: the FEATURES array, one
 * explicit import per feature folder (features/<id>/index.ts, which exports
 * `feature`), sorted by folder name so every OS gives the same file. No
 * side-effect registration anywhere.
 *
 *   npm run features:gen            regenerate
 *   node scripts/features/gen.mjs --check   exit 1 if registry.ts is stale (registry.test.ts runs this)
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '../../common/src/ships/features');
const OUT = join(DIR, 'registry.ts');

export function featureFolders(dir = DIR) {
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory() && existsSync(join(dir, name, 'index.ts')))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function render(folders) {
  const name = (f) => `f_${f.replace(/[^a-zA-Z0-9]/g, '_')}`;
  return [
    '// GENERATED by scripts/features/gen.mjs (npm run features:gen): do not edit by hand.',
    '// One import per features/<id>/index.ts (its `feature` export), sorted by folder. Only plan.ts and the barrel import this.',
    '',
    "import type { PartFeature } from './types.js';",
    ...folders.map((f) => `import { feature as ${name(f)} } from './${f}/index.js';`),
    '',
    `export const FEATURES: readonly PartFeature[] = [${folders.map(name).join(', ')}];`,
    '',
  ].join('\n');
}

/** The server and client halves: one barrel each (server/src/ships/features/index.ts, client/src/ships/features/index.ts) */
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const HALVES = [
  { dir: join(ROOT, 'server/src/ships/features'), exportName: 'serverFeature', type: 'ServerFeature', list: 'SERVER_FEATURES', where: 'server' },
  { dir: join(ROOT, 'client/src/ships/features'), exportName: 'clientFeature', type: 'ClientFeature', list: 'CLIENT_FEATURES', where: 'client' },
];

export function renderHalf(half, folders) {
  const name = (f) => `f_${f.replace(/[^a-zA-Z0-9]/g, '_')}`;
  return [
    '// GENERATED by scripts/features/gen.mjs (npm run features:gen): do not edit by hand.',
    `// One import per ${half.where}/src/ships/features/<id>/index.ts (its \`${half.exportName}\` export), sorted by folder.`,
    '',
    `import type { ${half.type} } from './types.js';`,
    ...folders.map((f) => `import { ${half.exportName} as ${name(f)} } from './${f}/index.js';`),
    '',
    `export const ${half.list}: readonly ${half.type}[] = [${folders.map(name).join(', ')}];`,
    '',
  ].join('\n');
}

const isMain = !!process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  const check = process.argv.includes('--check');
  const jobs = [{ out: OUT, text: render(featureFolders()), n: featureFolders().length }];
  for (const h of HALVES) {
    const folders = featureFolders(h.dir);
    jobs.push({ out: join(h.dir, 'index.ts'), text: renderHalf(h, folders), n: folders.length });
  }
  let stale = false;
  for (const j of jobs) {
    const have = existsSync(j.out) ? readFileSync(j.out, 'utf-8').replace(/\r\n/g, '\n') : '';
    const rel = j.out.slice(ROOT.length + 1).replace(/\\/g, '/');
    if (have === j.text) continue;
    if (check) { console.error(`features: ${rel} is stale; run npm run features:gen`); stale = true; }
    else { writeFileSync(j.out, j.text); console.log(`features: wrote ${rel} (${j.n} features).`); }
  }
  if (stale) process.exit(1);
  if (check) console.log('features: generated files are up to date.');
}
