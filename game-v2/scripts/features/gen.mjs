#!/usr/bin/env node
/**
 * Writes common/src/ships/features/registry.ts: the FEATURES array, one
 * explicit import per feature folder (features/<id>/index.ts, which exports
 * `feature`), sorted by folder name so every OS gives the same file. No
 * side-effect registration anywhere.
 *
 *   npm run features:gen            regenerate
 *   node scripts/features/gen.mjs --check   exit 1 if registry.ts is stale (registry.test.ts runs this)
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '../../common/src/ships/features');
const OUT = join(DIR, 'registry.ts');

export function featureFolders(dir = DIR) {
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory() && existsSync(join(dir, name, 'index.ts')))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function render(folders) {
  const name = (f) => `f_${f.replace(/[^a-zA-Z0-9]/g, '_')}`;
  return [
    '// GENERATED by scripts/features/gen.mjs (npm run features:gen): do not edit by hand.',
    '// One import per features/<id>/index.ts (its `feature` export), sorted by folder. Only plan.ts and the barrel import this.',
    '',
    "import type { PartFeature } from './types.js';",
    ...folders.map((f) => `import { feature as ${name(f)} } from './${f}/index.js';`),
    '',
    `export const FEATURES: readonly PartFeature[] = [${folders.map(name).join(', ')}];`,
    '',
  ].join('\n');
}

const isMain = !!process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  const text = render(featureFolders());
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf-8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (have !== text) { console.error('features: registry.ts is stale; run npm run features:gen'); process.exit(1); }
    console.log('features: registry.ts is up to date.');
  } else if (have !== text) {
    writeFileSync(OUT, text);
    console.log(`features: wrote registry.ts (${featureFolders().length} features).`);
  } else console.log('features: registry.ts is up to date.');
}
