// Regenerates docs/panels/index.md from docs/panels/entries/*.md. Plain Node, no dependencies.
// Run: npm run panels:index
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const PANELS = path.join(here, '..', 'docs', 'panels');
const ENTRIES = path.join(PANELS, 'entries');
const OUT = path.join(PANELS, 'index.md');

// Categories print in this order; any other category follows, alphabetically.
const CATEGORY_ORDER = ['graphics', 'gameplay', 'ui', 'performance', 'tools', 'website'];

function parseValue(raw) {
  if (raw === '') return null;
  if (raw === '[]') return [];
  if (raw.startsWith('"')) return JSON.parse(raw);
  return raw;
}

// Front matter: "key: value" lines, and "key:" followed by "- item" lines.
// Values are JSON strings (double-quoted), so the parser can stay this small.
function parseEntry(file) {
  const text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${path.basename(file)}: missing front matter`);
  const meta = {};
  let listKey = null;
  for (const line of m[1].split('\n')) {
    if (!line.trim()) continue;
    const item = line.match(/^- (.*)$/);
    if (item && listKey) { meta[listKey].push(parseValue(item[1].trim())); continue; }
    const kv = line.match(/^([a-z_]+):(?: (.*))?$/);
    if (!kv) throw new Error(`${path.basename(file)}: cannot parse "${line}"`);
    const [, key, raw] = kv;
    if (raw === undefined || raw.trim() === '') { meta[key] = []; listKey = key; }
    else { meta[key] = parseValue(raw.trim()); listKey = null; }
  }
  const body = m[2].trim();
  for (const k of ['date', 'category', 'topic']) {
    if (!meta[k]) throw new Error(`${path.basename(file)}: missing ${k}`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) throw new Error(`${path.basename(file)}: bad date`);
  return { ...meta, files: meta.files || [], body, file: path.basename(file) };
}

const cell = (s) => String(s ?? '').replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');
const catRank = (c) => {
  const i = CATEGORY_ORDER.indexOf(c);
  return i === -1 ? CATEGORY_ORDER.length : i;
};
const byRow = (a, b) =>
  catRank(a.category) - catRank(b.category) || a.category.localeCompare(b.category) || a.topic.localeCompare(b.topic);

const all = fs.readdirSync(ENTRIES).filter((f) => f.endsWith('.md')).sort().map((f) => parseEntry(path.join(ENTRIES, f)));
const rows = all.filter((e) => e.category !== 'notes' && e.category !== 'skipped');
const notes = all.filter((e) => e.category === 'notes');
const skipped = all.filter((e) => e.category === 'skipped');
const dates = [...new Set(rows.map((e) => e.date))].sort().reverse();

const out = [];
out.push('# Before/after panels', '');
out.push("Generated by npm run panels:index from docs/panels/entries/*.md: add an entry file, don't edit this file.", '');

for (const date of dates) {
  out.push(`## ${date}`, '');
  const dayRows = rows.filter((e) => e.date === date).sort(byRow);
  out.push('| category | topic | what changed | numbers | files |', '|---|---|---|---|---|');
  for (const e of dayRows) {
    const afterOnly = (e.status || '').split('; ').includes('after only');
    const topic = cell(e.topic) + (afterOnly ? ' *(after only)*' : '');
    out.push(`| ${cell(e.category)} | ${topic} | ${cell(e.body)} | ${cell(e.numbers)} | ${cell(e.files.join(', '))} |`);
  }
  out.push('');
  const dayNotes = notes.filter((e) => e.date === date).sort((a, b) => a.topic.localeCompare(b.topic));
  if (dayNotes.length) {
    out.push('**Notes**', '');
    for (const n of dayNotes) out.push(`- ${n.title ? `**${n.title}.** ` : ''}${n.body.replace(/\s*\n\s*/g, ' ')}`);
    out.push('');
  }
}

if (skipped.length) {
  out.push('## Skipped, and why', '');
  const sorted = [...skipped].sort((a, b) => b.date.localeCompare(a.date) || a.topic.localeCompare(b.topic));
  for (const s of sorted) out.push(`- **${s.title}** ${s.body.replace(/\s*\n\s*/g, ' ')}`);
  out.push('');
}

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`panels index: ${rows.length} rows, ${notes.length} notes, ${skipped.length} skipped -> ${path.relative(process.cwd(), OUT)}`);
